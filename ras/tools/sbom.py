"""Licence register and CycloneDX 1.5 SBOM from the installed Python packages, plus the parts pip does not
know about (model weights, FFmpeg). Run it inside the deployable image to describe what actually ships."""

from __future__ import annotations

import datetime as dt
import json
import platform
import re
import subprocess
import uuid
from importlib import metadata
from pathlib import Path

# licences that put conditions on distributing or hosting the software: flagged for a human decision
REVIEW = re.compile(r"\b(A?GPL|LGPL|MPL|EPL|CDDL|SSPL|BUSL|CC-BY-NC|Commons Clause)", re.I)
_CLASSIFIER = re.compile(r"License :: (?:OSI Approved :: )?(.+)")

NON_PIP = [  # bundled or system components that pip metadata does not cover
    {"name": "transkun-v2-weights", "version": "2.0", "license": "MIT",
     "note": "pretrained weights shipped inside the transkun package (Yan & Duan, 2024)"},
    {"name": "ffmpeg", "version": "system", "license": "LGPL-2.1-or-later / GPL-2.0-or-later (build dependent)",
     "note": "invoked as a separate program, not linked; Debian's build enables GPL parts"},
    # optional models (ras models download); vendored model code lives in ras/models/vendor
    {"name": "hft-transformer-weights", "version": "ismir2023-016_003", "license": "MIT",
     "note": "Sony hFT-Transformer, MAESTRO v3 checkpoint; model code vendored in ras/models/vendor/hft_model.py"},
    {"name": "kong-piano-transcription-weights", "version": "note_F1=0.9677_pedal_F1=0.9186", "license": "MIT",
     "note": "ByteDance high-resolution transcription with pedals, Zenodo record 4034264"},
    {"name": "piano-dynamic-estimation-weights", "version": "3beac7a2-fold0-e96", "license": "MIT",
     "note": "He et al. ICASSP 2026; encoder adapted upstream from GuzhengTech99 (no licence file): see DECISIONS.md"},
]


# packages whose metadata omits the licence; checked by hand against the project's LICENSE file
KNOWN = {"basic-pitch": "Apache-2.0"}


def _license(dist: metadata.Distribution) -> str:
    m = dist.metadata
    if (m.get("Name") or "").lower() in KNOWN:
        return KNOWN[m["Name"].lower()]
    expr = m.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [c.group(1) for c in map(_CLASSIFIER.match, m.get_all("Classifier") or []) if c]
    text = (m.get("License") or "").strip()
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    if text and len(text) < 80 and "\n" not in text:
        return text
    return "UNKNOWN (see package files)" if not text else text.splitlines()[0][:80]


def _ffmpeg_version() -> str:
    try:
        out = subprocess.run(["ffmpeg", "-version"], capture_output=True, text=True, timeout=10).stdout
        return out.split()[2] if out else "absent"
    except Exception:
        return "absent"


def collect() -> list[dict]:
    seen, rows = set(), []
    for d in metadata.distributions():
        name = (d.metadata.get("Name") or "").strip()
        if not name or name.lower() in seen or name.lower() == "ras":  # this project itself
            continue
        seen.add(name.lower())
        rows.append({"name": name, "version": d.version, "license": _license(d), "type": "python"})
    rows.sort(key=lambda r: r["name"].lower())
    for extra in NON_PIP:
        r = dict(extra, type="other")
        if r["name"] == "ffmpeg":
            r["version"] = _ffmpeg_version()
        rows.append(r)
    for r in rows:
        r["review"] = bool(REVIEW.search(r["license"])) or r["license"].startswith("UNKNOWN")
    return rows


def to_cyclonedx(rows: list[dict], name: str) -> dict:
    comps = []
    for r in rows:
        c = {"type": "library", "name": r["name"], "version": r["version"],
             "licenses": [{"license": {"name": r["license"]}}]}
        if r["type"] == "python":
            c["purl"] = f"pkg:pypi/{r['name'].lower()}@{r['version']}"
        comps.append(c)
    return {"bomFormat": "CycloneDX", "specVersion": "1.5", "serialNumber": f"urn:uuid:{uuid.uuid4()}",
            "version": 1, "metadata": {"timestamp": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                                       "component": {"type": "application", "name": f"ras ({name})"}},
            "components": comps}


def write_register(out_dir: Path, name: str) -> tuple[Path, Path, list[str]]:
    rows = collect()
    out_dir.mkdir(parents=True, exist_ok=True)
    cdx = out_dir / f"sbom-{name}.cdx.json"
    cdx.write_text(json.dumps(to_cyclonedx(rows, name), indent=1))
    flagged = [f"{r['name']} {r['version']}: {r['license']}" for r in rows if r["review"]]
    lines = [f"# Licence register ({name})\n",
             f"Generated by `ras sbom` on Python {platform.python_version()} ({platform.system()}). "
             f"{len(rows)} components; {len(flagged)} need a licence decision (copyleft or unknown).\n",
             "| component | version | licence | review |", "|---|---|---|---|"]
    lines += [f"| {r['name']} | {r['version']} | {r['license'].replace('|', '/')} | {'yes' if r['review'] else ''} |"
              for r in rows]
    md = out_dir / f"licences-{name}.md"
    md.write_text("\n".join(lines) + "\n")
    return md, cdx, flagged
